-- Contract term extraction proposals. Proposals are never authoritative until
-- reviewed and explicitly promoted into AI.CONTRACT_TERMS.
CREATE TABLE IF NOT EXISTS AI.CONTRACT_TERM_CANDIDATES (
    CANDIDATE_ID          VARCHAR(64) NOT NULL,
    CONTRACT_ID           VARCHAR(128) NOT NULL,
    DOCUMENT_ID           VARCHAR(128) NOT NULL,
    CONTRACT_VERSION      NUMBER(10,0) NOT NULL,
    TERM_CODE             VARCHAR(128) NOT NULL,
    TERM_VALUE            VARCHAR(4000),
    ROYALTY_PERCENTAGE    NUMBER(9,6),
    CURRENCY              VARCHAR(3),
    RATE_UNIT             VARCHAR(64),
    EFFECTIVE_FROM        DATE,
    EFFECTIVE_TO          DATE,
    CLAUSE_TYPE           VARCHAR(64) NOT NULL,
    CLAUSE_TEXT           VARCHAR(16000) NOT NULL,
    EVIDENCE_QUOTE        VARCHAR(8000) NOT NULL,
    SOURCE_CLAUSE_NUMBER  VARCHAR(128),
    SOURCE_PAGE_NUMBER    NUMBER(10,0) NOT NULL,
    APPROVAL_STATUS       VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    REVIEWED_BY           VARCHAR(256),
    REVIEWED_AT           TIMESTAMP_NTZ,
    CREATED_AT            TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT            TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CONTRACT_TERM_CANDIDATES PRIMARY KEY (CANDIDATE_ID),
    CONSTRAINT CK_CANDIDATE_ROYALTY CHECK (
      ROYALTY_PERCENTAGE IS NULL OR (ROYALTY_PERCENTAGE >= 0 AND ROYALTY_PERCENTAGE <= 100)
    ),
    CONSTRAINT CK_CANDIDATE_DATES CHECK (
      EFFECTIVE_TO IS NULL OR EFFECTIVE_FROM IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM
    )
)
COMMENT = 'Unapproved evidence-grounded contract clause and royalty-term extraction proposals';
