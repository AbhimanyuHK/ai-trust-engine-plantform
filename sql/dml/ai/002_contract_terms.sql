-- Effective-dated contract term DML templates.
-- Terms extracted by OCR/LLMs are proposals only. Insert/merge only after
-- Finance / Partner Relations review and required legal/signature verification.
-- Never overwrite historical terms when an amendment changes a rate.

-- Example values: replace all placeholders with reviewed contract data.
SET TERM_ID = 'replace-with-stable-term-id';
SET CONTRACT_ID = 'replace-with-contract-id';
SET PARTNER_ID = 'replace-with-partner-id';
SET CONTRACT_VERSION = 2;
SET TERM_CODE = 'ROYALTY_RATE';
SET TERM_VALUE = '12 percent';
SET ROYALTY_PERCENTAGE = 12.000000;
SET CURRENCY = NULL;
SET RATE_UNIT = 'PERCENT';
SET EFFECTIVE_FROM = '2026-07-01';
SET EFFECTIVE_TO = NULL;
SET SOURCE_DOCUMENT_ID = 'replace-with-approved-amendment-document-id';
SET SOURCE_CLAUSE_NUMBER = 'replace-with-clause';
SET SOURCE_PAGE_NUMBER = NULL;
SET REVIEWED_BY = 'replace-with-reviewer';
SET APPROVED_BY = 'replace-with-approver';

-- Insert a new versioned term. Keep prior rows and their effective periods.
MERGE INTO AI.CONTRACT_TERMS T
USING (
    SELECT
        $TERM_ID::VARCHAR AS TERM_ID,
        $CONTRACT_ID::VARCHAR AS CONTRACT_ID,
        $PARTNER_ID::VARCHAR AS PARTNER_ID,
        $CONTRACT_VERSION::NUMBER AS CONTRACT_VERSION,
        $TERM_CODE::VARCHAR AS TERM_CODE,
        $TERM_VALUE::VARCHAR AS TERM_VALUE,
        $ROYALTY_PERCENTAGE::NUMBER(9,6) AS ROYALTY_PERCENTAGE,
        $CURRENCY::VARCHAR AS CURRENCY,
        $RATE_UNIT::VARCHAR AS RATE_UNIT,
        $EFFECTIVE_FROM::DATE AS EFFECTIVE_FROM,
        $EFFECTIVE_TO::DATE AS EFFECTIVE_TO,
        $SOURCE_DOCUMENT_ID::VARCHAR AS SOURCE_DOCUMENT_ID,
        $SOURCE_CLAUSE_NUMBER::VARCHAR AS SOURCE_CLAUSE_NUMBER,
        $SOURCE_PAGE_NUMBER::NUMBER AS SOURCE_PAGE_NUMBER,
        $REVIEWED_BY::VARCHAR AS REVIEWED_BY,
        $APPROVED_BY::VARCHAR AS APPROVED_BY
) S
ON T.TERM_ID = S.TERM_ID
WHEN MATCHED THEN UPDATE SET
    T.TERM_VALUE = S.TERM_VALUE,
    T.ROYALTY_PERCENTAGE = S.ROYALTY_PERCENTAGE,
    T.CURRENCY = S.CURRENCY,
    T.RATE_UNIT = S.RATE_UNIT,
    T.EFFECTIVE_FROM = S.EFFECTIVE_FROM,
    T.EFFECTIVE_TO = S.EFFECTIVE_TO,
    T.SOURCE_CLAUSE_NUMBER = S.SOURCE_CLAUSE_NUMBER,
    T.SOURCE_PAGE_NUMBER = S.SOURCE_PAGE_NUMBER,
    T.REVIEWED_BY = S.REVIEWED_BY,
    T.APPROVED_BY = S.APPROVED_BY,
    T.APPROVAL_STATUS = 'APPROVED',
    T.APPROVED_AT = CURRENT_TIMESTAMP(),
    T.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    TERM_ID, CONTRACT_ID, PARTNER_ID, CONTRACT_VERSION, TERM_CODE,
    TERM_VALUE, ROYALTY_PERCENTAGE, CURRENCY, RATE_UNIT,
    EFFECTIVE_FROM, EFFECTIVE_TO, APPROVAL_STATUS, SOURCE_DOCUMENT_ID,
    SOURCE_CLAUSE_NUMBER, SOURCE_PAGE_NUMBER, REVIEWED_BY, APPROVED_BY,
    APPROVED_AT
) VALUES (
    S.TERM_ID, S.CONTRACT_ID, S.PARTNER_ID, S.CONTRACT_VERSION, S.TERM_CODE,
    S.TERM_VALUE, S.ROYALTY_PERCENTAGE, S.CURRENCY, S.RATE_UNIT,
    S.EFFECTIVE_FROM, S.EFFECTIVE_TO, 'APPROVED', S.SOURCE_DOCUMENT_ID,
    S.SOURCE_CLAUSE_NUMBER, S.SOURCE_PAGE_NUMBER, S.REVIEWED_BY, S.APPROVED_BY,
    CURRENT_TIMESTAMP()
);

-- Validation: approved terms for the same contract/code must not overlap.
-- Review returned rows and resolve conflicts before enabling royalty calculations.
SELECT A.CONTRACT_ID, A.TERM_CODE, A.TERM_ID AS TERM_A, B.TERM_ID AS TERM_B
FROM AI.CONTRACT_TERMS A
JOIN AI.CONTRACT_TERMS B
  ON A.CONTRACT_ID = B.CONTRACT_ID
 AND A.TERM_CODE = B.TERM_CODE
 AND A.TERM_ID < B.TERM_ID
 AND COALESCE(A.EFFECTIVE_TO, '9999-12-31'::DATE) >= B.EFFECTIVE_FROM
 AND COALESCE(B.EFFECTIVE_TO, '9999-12-31'::DATE) >= A.EFFECTIVE_FROM
WHERE UPPER(A.APPROVAL_STATUS) = 'APPROVED'
  AND UPPER(B.APPROVAL_STATUS) = 'APPROVED';

