-- Contract Intelligence: canonical Snowflake DDL
-- Run in the target database. Objects are intentionally idempotent.
-- Snowflake standard-table PK/UNIQUE constraints are informational; enforce
-- business uniqueness through deterministic IDs and idempotent MERGE operations.

CREATE SCHEMA IF NOT EXISTS AI;

CREATE TABLE IF NOT EXISTS AI.DOCUMENTS (
    DOCUMENT_ID          VARCHAR(128) NOT NULL,
    CONTRACT_ID          VARCHAR(128) NOT NULL,
    PARTNER_ID            VARCHAR(128),
    DOCUMENT_NAME         VARCHAR(1024) NOT NULL,
    DOCUMENT_TYPE         VARCHAR(32) NOT NULL DEFAULT 'ORIGINAL',
    DOCUMENT_VERSION      NUMBER(10,0) NOT NULL DEFAULT 1,
    CONTRACT_VERSION      NUMBER(10,0) NOT NULL DEFAULT 1,
    PARENT_DOCUMENT_ID    VARCHAR(128),
    SOURCE_URI            VARCHAR(2048) NOT NULL,
    CONTENT_HASH          VARCHAR(64) NOT NULL,
    EFFECTIVE_DATE        DATE,
    EXPIRY_DATE           DATE,
    INGESTION_STATUS      VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    APPROVAL_STATUS       VARCHAR(32) NOT NULL DEFAULT 'NOT_REQUIRED',
    PARSER_VERSION        VARCHAR(128),
    CHUNKING_VERSION      VARCHAR(128),
    CREATED_AT            TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT            TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DOCUMENTS PRIMARY KEY (DOCUMENT_ID),
    CONSTRAINT CK_DOCUMENT_VERSION CHECK (DOCUMENT_VERSION >= 1),
    CONSTRAINT CK_CONTRACT_VERSION CHECK (CONTRACT_VERSION >= 1)
)
COMMENT = 'Immutable source-document registry and version lineage for contract intelligence';

CREATE TABLE IF NOT EXISTS AI.DOCUMENT_CHUNKS (
    CHUNK_ID              VARCHAR(64) NOT NULL,
    CONTRACT_ID           VARCHAR(128) NOT NULL,
    DOCUMENT_NAME         VARCHAR(1024) NOT NULL,
    CHUNK_TEXT             VARCHAR,
    CHUNK_INDEX            NUMBER(10,0) NOT NULL,
    PAGE_NUMBER            NUMBER(10,0) NOT NULL,
    SECTION                VARCHAR(512),
    PARTNER_ID             VARCHAR(128),
    EFFECTIVE_DATE         DATE,
    EXPIRY_DATE            DATE,
    DOCUMENT_ID            VARCHAR(128),
    DOCUMENT_VERSION       NUMBER(10,0) NOT NULL DEFAULT 1,
    CONTRACT_VERSION       NUMBER(10,0) NOT NULL DEFAULT 1,
    DOCUMENT_TYPE          VARCHAR(32),
    SOURCE_URI             VARCHAR(2048),
    CONTENT_HASH           VARCHAR(64),
    CLAUSE_NUMBER          VARCHAR(128),
    PAGE_END               NUMBER(10,0),
    PARSER_VERSION         VARCHAR(128),
    CHUNKING_VERSION       VARCHAR(128),
    CREATED_AT             TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DOCUMENT_CHUNKS PRIMARY KEY (CHUNK_ID)
)
COMMENT = 'Versioned, page-aware contract evidence chunks indexed by Cortex Search';

CREATE TABLE IF NOT EXISTS AI.CONTRACT_TERMS (
    TERM_ID                VARCHAR(128) NOT NULL,
    CONTRACT_ID            VARCHAR(128) NOT NULL,
    PARTNER_ID              VARCHAR(128),
    CONTRACT_VERSION        NUMBER(10,0) NOT NULL,
    TERM_CODE               VARCHAR(128) NOT NULL,
    TERM_VALUE              VARCHAR(4000),
    ROYALTY_PERCENTAGE      NUMBER(9,6),
    CURRENCY                VARCHAR(3),
    RATE_UNIT               VARCHAR(64),
    EFFECTIVE_FROM          DATE NOT NULL,
    EFFECTIVE_TO            DATE,
    APPROVAL_STATUS         VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    SOURCE_DOCUMENT_ID      VARCHAR(128) NOT NULL,
    SOURCE_CLAUSE_NUMBER    VARCHAR(128),
    SOURCE_PAGE_NUMBER      NUMBER(10,0),
    REVIEWED_BY             VARCHAR(256),
    APPROVED_BY             VARCHAR(256),
    APPROVED_AT             TIMESTAMP_NTZ,
    CREATED_AT              TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT              TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CONTRACT_TERMS PRIMARY KEY (TERM_ID),
    CONSTRAINT CK_TERM_EFFECTIVE_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM),
    CONSTRAINT CK_ROYALTY_PERCENTAGE CHECK (ROYALTY_PERCENTAGE IS NULL OR (ROYALTY_PERCENTAGE >= 0 AND ROYALTY_PERCENTAGE <= 100))
)
COMMENT = 'Validated and approved effective-dated contract terms; authoritative source for downstream calculations';

CREATE TABLE IF NOT EXISTS AI.DOCUMENT_INGESTION_STATUS (
    RUN_ID                 VARCHAR(128) NOT NULL,
    DOCUMENT_ID            VARCHAR(128) NOT NULL,
    STAGE                  VARCHAR(64) NOT NULL,
    STATUS                 VARCHAR(32) NOT NULL,
    ATTEMPT                NUMBER(10,0) NOT NULL DEFAULT 1,
    ERROR_MESSAGE          VARCHAR(16000),
    STARTED_AT             TIMESTAMP_NTZ,
    COMPLETED_AT           TIMESTAMP_NTZ,
    UPDATED_AT             TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DOCUMENT_INGESTION_STATUS PRIMARY KEY (RUN_ID, DOCUMENT_ID, STAGE),
    CONSTRAINT CK_INGESTION_ATTEMPT CHECK (ATTEMPT >= 1)
)
COMMENT = 'Latest per-run, per-document, per-stage ingestion status and retry information';

-- Optional query-friendly view: only approved terms are eligible for downstream
-- transaction-date matching. The consuming calculation must still apply
-- EFFECTIVE_FROM <= transaction_date and (EFFECTIVE_TO IS NULL OR transaction_date <= EFFECTIVE_TO).
CREATE OR REPLACE VIEW AI.APPROVED_CONTRACT_TERMS AS
SELECT *
FROM AI.CONTRACT_TERMS
WHERE UPPER(APPROVAL_STATUS) = 'APPROVED';
