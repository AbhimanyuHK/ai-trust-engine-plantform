USE DATABASE TRUST_DB;
CREATE TABLE IF NOT EXISTS AI.RECOMMENDATIONS (
  RECOMMENDATION_ID STRING NOT NULL,
  WORKFLOW_ID STRING NOT NULL,
  CONTRACT_ID STRING,
  PARTNER_ID STRING,
  RECOMMENDATION_TYPE STRING NOT NULL,
  RECOMMENDATION_TEXT STRING NOT NULL,
  EVIDENCE VARIANT NOT NULL,
  MODEL_NAME STRING,
  MODEL_VERSION STRING,
  PROMPT_VERSION STRING,
  STATUS STRING NOT NULL DEFAULT 'DRAFT',
  CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT CK_RECOMMENDATION_STATUS CHECK
    (STATUS IN ('DRAFT','PENDING_APPROVAL','APPROVED','REJECTED','SUPERSEDED','ACTIVATED'))
);
