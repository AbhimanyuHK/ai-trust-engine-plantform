USE DATABASE TRUST_DB;
CREATE TABLE IF NOT EXISTS GOVERNANCE.APPROVAL_REQUESTS (
  APPROVAL_ID STRING NOT NULL,
  RECOMMENDATION_ID STRING NOT NULL,
  WORKFLOW_ID STRING NOT NULL,
  CHANGE_TYPE STRING NOT NULL,
  REQUIRED_ROLE STRING NOT NULL,
  STATUS STRING NOT NULL DEFAULT 'PENDING',
  PAYLOAD VARIANT NOT NULL,
  MODIFIED_PAYLOAD VARIANT,
  REVIEWER STRING,
  REVIEWER_ROLE STRING,
  DECISION_REASON STRING,
  CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  DECIDED_AT TIMESTAMP_NTZ,
  CONSTRAINT CK_APPROVAL_STATUS CHECK (STATUS IN ('PENDING','APPROVED','REJECTED','MODIFIED'))
);
CREATE TABLE IF NOT EXISTS GOVERNANCE.APPROVAL_AUDIT_LOG (
  EVENT_ID STRING NOT NULL,
  APPROVAL_ID STRING NOT NULL,
  EVENT_TYPE STRING NOT NULL,
  ACTOR STRING,
  ACTOR_ROLE STRING,
  REASON STRING,
  EVENT_PAYLOAD VARIANT,
  EVENT_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);
