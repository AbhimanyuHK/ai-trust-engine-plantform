SET DOCUMENT_ID = 'replace-with-document-id';
SET CONTRACT_ID = 'replace-with-contract-id';
SET PARTNER_ID = 'replace-with-partner-id';
SET DOCUMENT_NAME = 'replace-with-source-filename.pdf';
SET DOCUMENT_TYPE = 'ORIGINAL'; -- ORIGINAL or AMENDMENT
SET DOCUMENT_VERSION = 1;
SET CONTRACT_VERSION = 1;
SET PARENT_DOCUMENT_ID = NULL;
SET SOURCE_URI = 's3://replace-with-bucket/key.pdf';
SET CONTENT_HASH = 'replace-with-sha256';
SET EFFECTIVE_DATE = NULL;
SET EXPIRY_DATE = NULL;
SET PARSER_VERSION = 'pypdf-v1';
SET CHUNKING_VERSION = 'page-window-v2';

MERGE INTO AI.DOCUMENTS T
USING (
    SELECT
        $DOCUMENT_ID::VARCHAR AS DOCUMENT_ID,
        $CONTRACT_ID::VARCHAR AS CONTRACT_ID,
        $PARTNER_ID::VARCHAR AS PARTNER_ID,
        $DOCUMENT_NAME::VARCHAR AS DOCUMENT_NAME,
        $DOCUMENT_TYPE::VARCHAR AS DOCUMENT_TYPE,
        $DOCUMENT_VERSION::NUMBER AS DOCUMENT_VERSION,
        $CONTRACT_VERSION::NUMBER AS CONTRACT_VERSION,
        $PARENT_DOCUMENT_ID::VARCHAR AS PARENT_DOCUMENT_ID,
        $SOURCE_URI::VARCHAR AS SOURCE_URI,
        $CONTENT_HASH::VARCHAR AS CONTENT_HASH,
        $EFFECTIVE_DATE::DATE AS EFFECTIVE_DATE,
        $EXPIRY_DATE::DATE AS EXPIRY_DATE,
        $PARSER_VERSION::VARCHAR AS PARSER_VERSION,
        $CHUNKING_VERSION::VARCHAR AS CHUNKING_VERSION
) S
ON T.DOCUMENT_ID = S.DOCUMENT_ID
WHEN MATCHED AND T.CONTENT_HASH = S.CONTENT_HASH THEN UPDATE SET
    T.INGESTION_STATUS = 'PROCESSING',
    T.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    DOCUMENT_ID, CONTRACT_ID, PARTNER_ID, DOCUMENT_NAME, DOCUMENT_TYPE,
    DOCUMENT_VERSION, CONTRACT_VERSION, PARENT_DOCUMENT_ID, SOURCE_URI,
    CONTENT_HASH, EFFECTIVE_DATE, EXPIRY_DATE, INGESTION_STATUS,
    PARSER_VERSION, CHUNKING_VERSION
) VALUES (
    S.DOCUMENT_ID, S.CONTRACT_ID, S.PARTNER_ID, S.DOCUMENT_NAME, S.DOCUMENT_TYPE,
    S.DOCUMENT_VERSION, S.CONTRACT_VERSION, S.PARENT_DOCUMENT_ID, S.SOURCE_URI,
    S.CONTENT_HASH, S.EFFECTIVE_DATE, S.EXPIRY_DATE, 'PROCESSING',
    S.PARSER_VERSION, S.CHUNKING_VERSION
);

-- A document ID must identify immutable content. Stop if the same ID is reused
-- with a different hash; register the changed source as a new document/version.
-- This query should return zero rows before proceeding:
SELECT DOCUMENT_ID, CONTENT_HASH
FROM AI.DOCUMENTS
WHERE DOCUMENT_ID = $DOCUMENT_ID
  AND CONTENT_HASH <> $CONTENT_HASH;

-- Example stage status upsert. Use a unique RUN_ID for each ingestion execution.
SET RUN_ID = 'replace-with-run-id';
SET STAGE = 'CHUNK_PERSISTENCE';
SET STAGE_STATUS = 'SUCCEEDED'; -- PENDING, RUNNING, SUCCEEDED, FAILED, RETRYING
SET ATTEMPT = 1;
SET ERROR_MESSAGE = NULL;

MERGE INTO AI.DOCUMENT_INGESTION_STATUS T
USING (
    SELECT
        $RUN_ID::VARCHAR AS RUN_ID,
        $DOCUMENT_ID::VARCHAR AS DOCUMENT_ID,
        $STAGE::VARCHAR AS STAGE,
        $STAGE_STATUS::VARCHAR AS STATUS,
        $ATTEMPT::NUMBER AS ATTEMPT,
        $ERROR_MESSAGE::VARCHAR AS ERROR_MESSAGE
) S
ON T.RUN_ID = S.RUN_ID
AND T.DOCUMENT_ID = S.DOCUMENT_ID
AND T.STAGE = S.STAGE
WHEN MATCHED THEN UPDATE SET
    T.STATUS = S.STATUS,
    T.ATTEMPT = S.ATTEMPT,
    T.ERROR_MESSAGE = S.ERROR_MESSAGE,
    T.COMPLETED_AT = IFF(S.STATUS IN ('SUCCEEDED', 'FAILED', 'CANCELLED'), CURRENT_TIMESTAMP(), NULL),
    T.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    RUN_ID, DOCUMENT_ID, STAGE, STATUS, ATTEMPT, ERROR_MESSAGE,
    STARTED_AT, COMPLETED_AT, UPDATED_AT
) VALUES (
    S.RUN_ID, S.DOCUMENT_ID, S.STAGE, S.STATUS, S.ATTEMPT, S.ERROR_MESSAGE,
    CURRENT_TIMESTAMP(),
    IFF(S.STATUS IN ('SUCCEEDED', 'FAILED', 'CANCELLED'), CURRENT_TIMESTAMP(), NULL),
    CURRENT_TIMESTAMP()
);

